import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const SRC = join(ROOT, 'src');
export const GENERATED = join(SRC, 'generated');

export const HEADER = `// AUTO-GENERATED by scripts/gen — do not edit. Sources: features/*, shell/*. Run \`pnpm gen\`.\n`;

export function listFeatures() {
  const dir = join(SRC, 'features');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => !name.startsWith('_') && !name.startsWith('.') && statSync(join(dir, name)).isDirectory())
    .sort();
}

export function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

export function writeGenerated(file, content) {
  mkdirSync(GENERATED, { recursive: true });
  const path = join(GENERATED, file);
  const previous = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (previous !== content) writeFileSync(path, content);
  return { path: relative(ROOT, path), changed: previous !== content };
}

export function importPath(absPath) {
  return '@/' + relative(SRC, absPath).replace(/\\/g, '/').replace(/\.(ts|tsx)$/, '');
}

export class GenReport {
  errors = [];
  warnings = [];
  outputs = [];
  error(msg) {
    this.errors.push(msg);
  }
  warn(msg) {
    this.warnings.push(msg);
  }
}

/** Flattens `{a: {b: 1}}` into `['a.b']`. */
export function flattenKeys(obj, prefix = '') {
  const out = [];
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object' && !Array.isArray(v)) out.push(...flattenKeys(v, key));
    else out.push(key);
  }
  return out;
}
